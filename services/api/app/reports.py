def render_comparison_report(comparison: dict[str, Any]) -> str:
    """Markdown report for a stored comparison (variants × metrics + verdicts)."""
    base = comparison.get("baseConfig") or {}
    results = comparison.get("results") or {}
    variants = results.get("variants") or []
    out: list[str] = []
    out.append(f"# Comparison Report — {comparison.get('name') or comparison.get('id')}")
    out.append("")
    out.append(
        f"Base experiment: **{base.get('name')}** "
        f"(scheduler `{(base.get('scheduler') or {}).get('type')}`, "
        f"{len(base.get('tasks', []))} tasks, duration {base.get('duration')})."
    )
    out.append("")
    out.append("Variant overrides are deep-merged over the base config "
               "(dicts merge recursively, lists are replaced).")
    out.append("")

    metric_keys = list(COMPARISON_METRICS)
    header = ["Metric"] + [v.get("label", "?") for v in variants]
    rows: list[list[Any]] = []
    for key in metric_keys:
        rows.append([key] + [(v.get("metrics") or {}).get(key) for v in variants])
    out.append("## Per-variant metrics")
    out.append("")
    out.append(_table(header, rows))
    out.append("")

    best = results.get("bestPerMetric") or {}
    if best:
        out.append("## Best per metric")
        out.append("")
        out.append(
            _table(
                ["Metric", "Best variant", "Value", "Direction"],
                [
                    [key, entry.get("label"), entry.get("value"),
                     COMPARISON_METRICS.get(key)]
                    for key, entry in best.items()
                ],
            )
        )
        out.append("")

    deltas = results.get("deltasVsFirst") or []
    if deltas:
        out.append("## Delta vs first variant (baseline)")
        out.append("")
        out.append(
            _table(
                ["Variant"] + metric_keys,
                [[d.get("label")] + [d.get("metrics", {}).get(k) for k in metric_keys]
                 for d in deltas],
            )
        )
        out.append("")

    starved = [v for v in variants if (v.get("starvedTaskIds") or [])]
    if starved:
        out.append("## Starvation per variant")
        out.append("")
        for v in starved:
            out.append(f"- **{v.get('label')}**: starved — "
                       f"{', '.join(v['starvedTaskIds'])}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


